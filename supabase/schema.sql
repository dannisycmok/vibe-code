-- CRUD Studio schema for Supabase/PostgreSQL.
-- Run this in the Supabase dashboard: SQL Editor -> New query -> Run.

create table if not exists public.products (
  pid bigint generated by default as identity primary key,
  pname text not null,
  description text not null default '',
  price numeric(12, 2) not null default 0,
  qty integer not null default 0,
  constraint products_pname_not_blank check (length(btrim(pname)) > 0),
  constraint products_price_non_negative check (price >= 0),
  constraint products_qty_non_negative check (qty >= 0)
);

create table if not exists public.users (
  uid bigint generated by default as identity primary key,
  uname text not null,
  email text not null,
  password text not null,
  constraint users_uname_not_blank check (length(btrim(uname)) > 0),
  constraint users_email_key unique (email)
);

create table if not exists public.orders (
  oid bigint generated by default as identity primary key,
  uid bigint not null,
  pid bigint not null,
  order_date timestamptz not null default now(),
  constraint orders_uid_fkey foreign key (uid)
    references public.users(uid) on update cascade on delete restrict,
  constraint orders_pid_fkey foreign key (pid)
    references public.products(pid) on update cascade on delete restrict
);

create index if not exists idx_orders_uid on public.orders(uid);
create index if not exists idx_orders_pid on public.orders(pid);
create index if not exists idx_orders_order_date on public.orders(order_date);

-- The API uses the service_role key, which bypasses RLS.
-- Enabling RLS without public policies blocks direct anon/authenticated access.
alter table public.products enable row level security;
alter table public.users enable row level security;
alter table public.orders enable row level security;

grant usage on schema public to service_role;
grant select, insert, update, delete on public.products to service_role;
grant select, insert, update, delete on public.users to service_role;
grant select, insert, update, delete on public.orders to service_role;
grant usage, select on all sequences in schema public to service_role;
